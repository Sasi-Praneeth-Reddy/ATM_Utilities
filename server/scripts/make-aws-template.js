#!/usr/bin/env node
/**
 * Generates aws/atm-data.template.json (a CloudFormation template) from the table definitions in
 * server/awsStore.js, so the real tables can never drift from what the code expects.
 *
 *   cd server
 *   node scripts/make-aws-template.js            # rewrites ../aws/atm-data.template.json
 *
 * The template creates: one DynamoDB table per entry in TABLE_DEFS (on-demand billing, point-in-time
 * recovery ON, deletion protection ON, kept if the stack is deleted), the least-privilege IAM user the
 * Firebase backend signs in as (atm-data-writer: DynamoDB access to ONLY these tables), and, if you give
 * an email, an AWS Budget alert. Access keys are NOT created here (they would end up in stack outputs);
 * docs/AWS-DATA.md shows the one CLI command that creates them.
 */
const fs = require('fs');
const path = require('path');
const store = require('../awsStore');

const types = Object.keys(store.TABLE_DEFS);
const logical = (type) => `${type}Table`;

const tpl = {
  AWSTemplateFormatVersion: '2010-09-09',
  Description: 'Around Town Movers scheduler: Leads and Storage-market data (DynamoDB) plus the IAM user the Firebase backend uses. Generated by server/scripts/make-aws-template.js - do not edit by hand.',
  Parameters: {
    Prefix: { Type: 'String', Default: 'atm-', AllowedPattern: '^[a-z0-9-]*$', Description: 'Prefix for every table and the IAM user. Use atm-stg- for a staging copy. Must match ATM_DDB_PREFIX in the app.' },
    AlertEmail: { Type: 'String', Default: '', Description: 'Optional. Email address to warn when this AWS ACCOUNT\'s monthly cost passes 80% of MonthlyBudgetUsd. Leave empty to skip the budget.' },
    MonthlyBudgetUsd: { Type: 'Number', Default: 5, Description: 'Monthly cost (USD) for the whole AWS account that the budget alert watches.' },
  },
  Conditions: { HasAlertEmail: { 'Fn::Not': [{ 'Fn::Equals': [{ Ref: 'AlertEmail' }, ''] }] } },
  Resources: {},
  Outputs: {},
};

const tableActions = [
  'dynamodb:GetItem', 'dynamodb:BatchGetItem', 'dynamodb:PutItem', 'dynamodb:UpdateItem', 'dynamodb:DeleteItem',
  'dynamodb:BatchWriteItem', 'dynamodb:Query', 'dynamodb:Scan', 'dynamodb:DescribeTable',
];
const resources = [];

for (const type of types) {
  const def = store.TABLE_DEFS[type];
  const spec = store.tableSpec(type);
  const props = {
    TableName: { 'Fn::Sub': `\${Prefix}${def.table}` },
    BillingMode: 'PAY_PER_REQUEST',
    AttributeDefinitions: spec.AttributeDefinitions,
    KeySchema: spec.KeySchema,
    PointInTimeRecoverySpecification: { PointInTimeRecoveryEnabled: true },
    DeletionProtectionEnabled: true,
    Tags: [{ Key: 'app', Value: 'atm-scheduler' }, { Key: 'entity', Value: type }],
  };
  if (spec.GlobalSecondaryIndexes.length) props.GlobalSecondaryIndexes = spec.GlobalSecondaryIndexes;
  tpl.Resources[logical(type)] = { Type: 'AWS::DynamoDB::Table', DeletionPolicy: 'Retain', UpdateReplacePolicy: 'Retain', Properties: props };
  resources.push({ 'Fn::GetAtt': [logical(type), 'Arn'] });
  if (spec.GlobalSecondaryIndexes.length) resources.push({ 'Fn::Sub': `\${${logical(type)}.Arn}/index/*` });
  tpl.Outputs[`${logical(type)}Name`] = { Value: { Ref: logical(type) } };
}

tpl.Resources.DataWriterUser = {
  Type: 'AWS::IAM::User',
  Properties: {
    UserName: { 'Fn::Sub': '${Prefix}data-writer' },
    Policies: [{
      PolicyName: 'atm-dynamodb-tables-only',
      PolicyDocument: { Version: '2012-10-17', Statement: [{ Effect: 'Allow', Action: tableActions, Resource: resources }] },
    }],
  },
};
tpl.Outputs.DataWriterUserName = { Value: { Ref: 'DataWriterUser' }, Description: 'Create its access key with: aws iam create-access-key --user-name <this value>' };

tpl.Resources.CostBudget = {
  Type: 'AWS::Budgets::Budget',
  Condition: 'HasAlertEmail',
  Properties: {
    Budget: {
      BudgetName: { 'Fn::Sub': '${Prefix}monthly-cost' }, BudgetType: 'COST', TimeUnit: 'MONTHLY',
      BudgetLimit: { Amount: { Ref: 'MonthlyBudgetUsd' }, Unit: 'USD' },
    },
    NotificationsWithSubscribers: [{
      Notification: { NotificationType: 'ACTUAL', ComparisonOperator: 'GREATER_THAN', Threshold: 80, ThresholdType: 'PERCENTAGE' },
      Subscribers: [{ SubscriptionType: 'EMAIL', Address: { Ref: 'AlertEmail' } }],
    }],
  },
};

const out = path.resolve(__dirname, '../../aws/atm-data.template.json');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, `${JSON.stringify(tpl, null, 2)}\n`);
console.log(`Wrote ${out} (${types.length} tables).`);
